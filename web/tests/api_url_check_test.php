<?php
declare(strict_types=1);

/**
 * url_check API の回帰テスト。
 * UC-1: 内部アドレス(127.0.0.1)は SSRF 対策で 400 拒否（2026-07-20 更新）
 * UC-2: メタデータ/プライベートアドレスも 400 拒否
 * UC-3: ftp:// → 400
 * UC-4: javascript:alert(1) → 400
 * UC-5: null/missing url → 400
 * UC-6: empty string → 400
 *
 * 注: 公開ホストへの疎通正常系は実 curl が走りネットワーク依存で不安定なため、
 *     ホスト検証ロジックは api_url_check_ssrf_test.php の url_check_is_safe_host()
 *     ユニットテストで網羅する。ここでは拒否系(実 curl を発火しない経路)を固定する。
 */

require_once __DIR__ . '/helpers.php';

tet2_test_boot();
load_api('url_check');

// -----------------------------------------------------------------------
// UC-1: 内部アドレス(ループバック)は SSRF 対策で 400 拒否
// -----------------------------------------------------------------------
$r = call_handler('url_check_handle', ['url' => 'http://127.0.0.1/'], 'operator');
check($r['code'] === 400, 'UC-1: ループバック(127.0.0.1) → 400(SSRF拒否)');

// -----------------------------------------------------------------------
// UC-2: クラウドメタデータ/プライベートは 400 拒否
// -----------------------------------------------------------------------
$r = call_handler('url_check_handle', ['url' => 'http://169.254.169.254/latest/meta-data/'], 'operator');
check($r['code'] === 400, 'UC-2: メタデータ(169.254.169.254) → 400(SSRF拒否)');
$r = call_handler('url_check_handle', ['url' => 'http://10.0.0.1/'], 'operator');
check($r['code'] === 400, 'UC-2: プライベート(10.0.0.1) → 400(SSRF拒否)');

// -----------------------------------------------------------------------
// UC-3: ftp:// → 400
// -----------------------------------------------------------------------
$r = call_handler('url_check_handle', ['url' => 'ftp://example.com/file.txt'], 'operator');
check($r['code'] === 400, 'UC-3: ftp:// → 400');

// -----------------------------------------------------------------------
// UC-4: javascript:alert(1) → 400
// -----------------------------------------------------------------------
$r = call_handler('url_check_handle', ['url' => 'javascript:alert(1)'], 'operator');
check($r['code'] === 400, 'UC-4: javascript:alert(1) → 400');

// -----------------------------------------------------------------------
// UC-5: null/missing url → 400
// -----------------------------------------------------------------------
$r = call_handler('url_check_handle', [], 'operator');
check($r['code'] === 400, 'UC-5: missing url → 400');

// -----------------------------------------------------------------------
// UC-6: empty string → 400
// -----------------------------------------------------------------------
$r = call_handler('url_check_handle', ['url' => ''], 'operator');
check($r['code'] === 400, 'UC-6: empty string → 400');

echo "ALL TESTS PASSED\n";
